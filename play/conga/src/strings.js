export const stringsFor = (lang) => STRINGS[lang] ?? STRINGS.en;


export const fill = (s, vars = {}) => String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));


export function cardName(T, card) {
  const f = String(card);
  if (f === 'JK1' || f === 'JK2') return T.joker;
  const suit = f.slice(-1);
  const rank = f.slice(0, -1);
  return fill(T.cardLabel, { rank, suit: T[`suit_${suit}`] || suit });
}
